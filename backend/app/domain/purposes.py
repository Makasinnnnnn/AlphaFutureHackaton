def match_purpose_rules(text: str) -> list[tuple[str, int]]:
    """Простой классификатор по ключевым словам: возвращает цели по убыванию совпадений."""
    t = text.lower()
    hits = []
    for code, p in PURPOSES.items():
        n = sum(1 for k in p["keywords"] if re.search(re.escape(k), t))
        if n:
            hits.append((code, n))
    return sorted(hits, key=lambda x: -x[1])
